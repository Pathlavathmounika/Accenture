package com.tnsif.loops;

public class Loops {
// for loop
	public static void main(String[] args) {
	      for(int i = 1; i<=10; i++) {
	    	  System.out.print(i+",");
	      }

	      // while loop
	      int i = 1;
	      while(i<=5) {
	    	  System.out.println(i);
	    	  i++;
	      }
	      
	      // do-while loop
	      int j=1;
	      do{
	    	  System.out.println(j);
	    	  j++;
	    	 }while(j<=10);
	}

}
